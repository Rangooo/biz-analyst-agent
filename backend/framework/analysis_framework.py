def pick_template(industry_hint: str) -> str:
    """根据行业线索匹配模板 key。"""
    if not industry_hint:
        return "generic"
    h = industry_hint.lower()
    for key, tpl in INDUSTRY_TEMPLATES.items():
        if key == "generic":
            continue
        for alias in tpl["aliases"]:
            if alias in h:
                return key
    return "generic"


def get_template(key: str) -> dict:
    return INDUSTRY_TEMPLATES.get(key, INDUSTRY_TEMPLATES["generic"])
