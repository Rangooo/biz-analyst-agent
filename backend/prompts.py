def resolve_prompt(query: str) -> list[dict]:
    """实体消歧 —— 用户输入可能模糊（如"蚂蚁"→蚂蚁集团/蚂蚁数科/蚂蚁国际），
    返回候选实体列表 + 默认选择 + 是否需用户确认。"""
    sys = ("你是实体识别助手。给定一个可能模糊的公司/行业名，列出它可能指代的真实实体。"
           "只输出 JSON，不要解释。")
    user = f"""输入：{query}

请输出 JSON：
{{
  "ambiguous": true/false (是否存在多个合理候选，需要用户确认),
  "default": "最可能指代的实体规范名",
  "candidates": [
    {{
      "name": "实体规范名",
      "kind": "company/industry",
      "is_public": true/false,
      "ticker": "股票代码(无则空)",
      "note": "一句话说明这是哪个主体(业务/上市地/关系)，帮用户区分"
    }}
  ]
}}

规则：
- 若输入已明确指向唯一实体（如"奇富科技""苹果""中国新能源汽车行业"），ambiguous=false，candidates 只含该实体。
- 若输入有歧义（简称/多主体同名，如"蚂蚁""字节""中信"），ambiguous=true，列出 2-4 个最可能候选，default 选最知名的。
- 候选需是真实存在的主体，不要编造。
- **品牌名与上市主体名可能不同**：如"蜜雪冰城"是品牌名，上市主体是"蜜雪集团"(02097.HK)；"喜茶"→"茶百道"等。若输入是知名消费品牌，务必识别其对应的上市主体（母公司/控股公司/主体公司），不要因品牌名≠公司名就判 is_public=false。近期 IPO 的品牌（1-2 年内）尤其注意。
- **同一实体的不同名必须合并为一条**：如「蚂蚁科技集团」与「Ant Group」、「深度求索」与「DeepSeek」、「字节跳动」与「ByteDance」，无论中英文/括号格式差异，都是同一主体。name 取最规范名，note 注明别名；**绝对禁止把同一主体列成多条**。"""
    return [{"role": "system", "content": sys}, {"role": "user", "content": user}]


def extract_financials_prompt(profile_json: str, evidence_digest: str) -> list[dict]:
    """从已采集证据中抽取多年财务时序（营收/净利润/经营利润），用于报告图表。
    适用 A股/港股/非美股（SEC 无结构化数据时），数据来自新闻/公告/研报文本。"""
    sys = ("你是财务数据抽取员。从证据文本中抽取该公司多年关键财务指标，"
           "只输出 JSON 数组，按年度升序。不要编造，无数据则对应字段为 null。")
    user = f"""分析对象：{profile_json}

证据（含来源等级与时效）：
{evidence_digest}

请抽取该公司最近 3-6 年年度数据，并在证据包含时补充最新 2-4 个季度/中期数据（如 2026Q1、2025Q4），输出 JSON：
[
  {{"period": "2022", "revenue": 数值(原始货币单位，元), "net_income": 数值, "operating_income": 数值或null}},
  {{"period": "2026Q1", "revenue": 数值, "net_income": 数值, "operating_income": 数值或null}},
  ...
]

规则：
- 数值用原始货币单位（元，不要"亿/万"换算后字符串，要纯数字如 416161000000）。
- 只用证据里出现的数字，每个数字可溯源；年份取财年(fy)。
- 季度/中期数据 period 用 `YYYYQ1` / `YYYYH1` / `YYYYQ4` 格式；不要把季度数据年化。
- 若证据不含多年财务数据，返回空数组 []。
- A股/港股货币为人民币，美股为美元。"""
    return [{"role": "system", "content": sys}, {"role": "user", "content": user}]


