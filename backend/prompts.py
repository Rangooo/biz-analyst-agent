def narrative_polish_prompt(full_draft: str) -> list[dict]:
    """【改进3】段间衔接微手术——不再全文重写，只生成段间过渡语与修复指令。
    三段独立生成后做整篇润色——但只动衔接，不重写内容。
    输出 JSON：包含 3-4 个精准的文本替换/插入指令。
    如果发现跨段重复的判断或数字，也输出删除指令。

    与旧版对比：
    - 旧版：传入全文(~6000字) → LLM 全文重写 → token 消耗高、容易引入错误
    - 新版：传入三段首尾摘要(~2000字) → LLM 只输出修补指令 → token 降60%、更精准
    """
    # 提取三段的首尾关键句（各200字），供 LLM 判断衔接是否断裂
    import re
    sections = re.split(r'(?=^## )', full_draft, flags=re.MULTILINE)
    sections = [s.strip() for s in sections if s.strip()]

    # 构建精简的段间上下文
    boundaries: list[str] = []
    for i, sec in enumerate(sections):
        lines = sec.split('\n')
        title = lines[0] if lines else f"段{i+1}"
        # 取每段最后 150 字 + 下一段开头 150 字
        tail = sec[-200:] if len(sec) > 200 else sec
        head = sec[:200] if len(sec) > 200 else sec
        boundaries.append(f"--- {title} ---\n尾部: ...{tail[-150:]}\n头部: {head[:150]}...")

    boundary_text = "\n\n".join(boundaries)

    sys = ("你是终审编辑，负责修复分段生成的研报的段间断裂与跨段重复。"
           "你不重写全文，只产出精准的修补指令。只输出 JSON，不要解释。")
    user = f"""以下是分段生成的研报各段首尾（段间可能有断裂/重复/风格不一）：

{boundary_text}

请生成修补指令，输出 JSON：
{{
  "transitions": [
    {{
      "位置": "在XX段结尾 / 在XX段开头之前",
      "操作": "插入过渡句 / 删除重复",
      "内容": "具体的过渡句文本 或 要删除的重复文本的关键短语"
    }}
  ],
  "style_fixes": [
    "全文风格统一修正（如有），每条不超过20字，最多3条"
  ],
  "thesis_check": "执行摘要论点是否被核心发现支撑(是/否/部分)，若否给出1句修正建议"
}}

规则：
- transitions 最多 4 条，每条过渡句不超过 40 字
- 过渡句要承上启下（如"基于上述事实基础，以下核心发现将逐层展开…"）
- 删除重复时只给出要删的关键短语（20字内），调用方用字符串匹配定位
- 不要改动 [^N] 脚注、(置信度X%) 标签、数据数字
- 只处理段间衔接问题，不要修改段内内容"""
    return [{"role": "system", "content": sys}, {"role": "user", "content": user}]


